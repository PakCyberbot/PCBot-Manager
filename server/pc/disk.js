let scan = loadScan();
const job = { running: false, roots: [], files: 0, dirs: 0, bytes: 0, errors: 0, current: '', startedAt: null, phase: 'idle' };

function loadScan() {
  try { return JSON.parse(fs.readFileSync(SCAN_FILE, 'utf8')); } catch { return null; }
}

function lower(p) { return p.toLowerCase(); }
function isUnder(child, parent) {
  const c = lower(child); const p = lower(parent).replace(/\\+$/, '');
  return c === p || c.startsWith(p + '\\');
}

async function mapLimit(items, limit, fn) {
  const results = new Array(items.length);
  let i = 0;
  const workers = Array.from({ length: Math.min(limit, items.length) }, async () => {
    while (i < items.length) { const idx = i++; results[idx] = await fn(items[idx], idx); }
  });
  await Promise.all(workers);
  return results;
}

async function quickHash(file, size) {
  const fh = await fsp.open(file, 'r');
  try {
    const chunk = 1024 * 1024;
    const a = Buffer.alloc(Math.min(chunk, size));
    await fh.read(a, 0, a.length, 0);
    const b = Buffer.alloc(Math.min(chunk, size));
    await fh.read(b, 0, b.length, Math.max(0, size - chunk));
    return crypto.createHash('sha1').update(a).update(b).update(String(size)).digest('hex');
  } finally { await fh.close(); }
}

async function walk(roots) {
  const own = new Map();
  const largeFiles = [];
  const dupPool = [];
  const types = {};
  const artifacts = [];
  const appCaches = [];
  const oldDownloads = [];
  const downloadsDir = lower(path.join(HOME, 'Downloads'));
  const now = Date.now();
  const skip = new Set([lower(TRASH_ROOT)]);
  // Inside these, folders like node_modules/venvs are part of the cache itself (counted there), not project artifacts.
  const knownRoots = new Set(KNOWN_LOCATIONS.map((k) => lower(k.path)));

  const queue = roots.map((r) => [r, { inArtifact: false, inCache: false, inKnown: false }]);
  let active = 0;

  await new Promise((resolve) => {
    const pump = () => {
      while (active < 48 && queue.length) {
        const [dir, flags] = queue.pop();
        active++;
        processDir(dir, flags).catch(() => { job.errors++; }).finally(() => {
          active--;
          if (queue.length === 0 && active === 0) resolve(); else pump();
        });
      }
      if (queue.length === 0 && active === 0) resolve();
    };
    pump();
  });

  async function processDir(dir, flags) {
    job.current = dir;
    job.dirs++;
    let entries;
    try { entries = await fsp.readdir(dir, { withFileTypes: true }); } catch { job.errors++; own.set(lower(dir), 0); return; }
    const names = new Set(entries.map((e) => e.name.toLowerCase()));
    // A folder containing pyvenv.cfg is itself a virtualenv - decide before queueing children.
    const installArea = isInstallArea(dir);
    const selfIsVenv = !flags.inArtifact && !flags.inKnown && !installArea && names.has('pyvenv.cfg');
    if (selfIsVenv) artifacts.push({ kind: 'venv', path: dir, project: path.dirname(dir) });
    const inArtifact = flags.inArtifact || selfIsVenv;
    const files = [];
    for (const e of entries) {
      if (e.isSymbolicLink()) continue;
      const full = path.join(dir, e.name);
      if (e.isDirectory()) {
        if (skip.has(lower(full))) continue;
        const nameL = e.name.toLowerCase();
        let kind = null;
        const inKnown = flags.inKnown || knownRoots.has(lower(full));
        if (!inArtifact && !inKnown && !installArea) {
          // A node_modules nested inside another node_modules (e.g. a globally installed CLI under
          // nvm\vX\node_modules\pkg\node_modules) is part of an installed package, not a project artifact.
          if (nameL === 'node_modules' && names.has('package.json') && !NESTED_NODE_MODULES.test(dir + '\\')) kind = 'node_modules';
          else if (nameL === 'target' && names.has('cargo.toml')) kind = 'rust_target';
          else if ((nameL === 'build' || nameL === '.gradle') && (names.has('build.gradle') || names.has('build.gradle.kts') || names.has('settings.gradle') || names.has('settings.gradle.kts'))) kind = 'gradle_build';
          else if ((nameL === 'bin' || nameL === 'obj') && [...names].some((n) => n.endsWith('.csproj') || n.endsWith('.fsproj'))) kind = 'dotnet_build';
          else if (BUILD_CACHE_NAMES.has(nameL)) kind = 'build_cache';
        }
        const isAppCache = !flags.inCache && !inArtifact && CACHE_DIR_NAMES.has(nameL) && (isUnder(full, LOCAL) || isUnder(full, ROAMING));
        if (kind) artifacts.push({ kind, path: full, project: dir });
        if (isAppCache) appCaches.push({ path: full });
        queue.push([full, { inArtifact: inArtifact || !!kind, inCache: flags.inCache || isAppCache, inKnown }]);
      } else if (e.isFile()) {
        files.push(full);
      }
    }
    let bytes = 0;
    const inDownloads = isUnder(dir, downloadsDir);
    await mapLimit(files, 32, async (full) => {
      let st;
      try { st = await fsp.lstat(full); } catch { job.errors++; return; }
      const size = st.size;
      bytes += size;
      job.files++;
      const ext = path.extname(full).slice(1).toLowerCase();
      const g = EXT_TO_GROUP[ext] || 'Other';
      if (!types[g]) types[g] = { bytes: 0, count: 0 };
      types[g].bytes += size; types[g].count++;
      if (!inArtifact) {
        if (size >= LARGE_FILE_BYTES) largeFiles.push({ path: full, size, mtime: st.mtimeMs, type: g });
        if (size >= DUP_MIN_BYTES) dupPool.push({ path: full, size, mtime: st.mtimeMs });
        if (inDownloads && (now - st.mtimeMs) / 86400000 > OLD_DOWNLOAD_DAYS) oldDownloads.push({ path: full, size, mtime: st.mtimeMs, type: g });
      }
    });
    job.bytes += bytes;
    own.set(lower(dir), bytes);
  }

  return { own, largeFiles, dupPool, types, artifacts, appCaches, oldDownloads };
}

function aggregate(own) {
  const keys = [...own.keys()];
  keys.sort((a, b) => b.split('\\').length - a.split('\\').length);
  const total = new Map(own);
  for (const k of keys) {
    const i = k.lastIndexOf('\\');
    if (i <= 2) continue;
    const parent = k.slice(0, i);
    if (total.has(parent)) total.set(parent, total.get(parent) + total.get(k));
  }
  return total;
}

async function findDuplicates(pool) {
  const bySize = new Map();
  for (const f of pool) { if (!bySize.has(f.size)) bySize.set(f.size, []); bySize.get(f.size).push(f); }
  const groups = [];
  for (const [size, files] of bySize) {
    if (files.length < 2) continue;
    const byHash = new Map();
    for (const f of files) {
      try { const h = await quickHash(f.path, size); if (!byHash.has(h)) byHash.set(h, []); byHash.get(h).push(f); } catch { /* unreadable / locked */ }
    }
    for (const g of byHash.values()) if (g.length > 1) groups.push({ size, files: g, wasted: size * (g.length - 1) });
  }
  return groups.sort((a, b) => b.wasted - a.wasted);
}

async function runScan(roots) {
  if (job.running) throw new Error('A scan is already running');
  roots = roots.map((r) => path.resolve(r));
  for (const r of roots) if (!fs.existsSync(r)) throw new Error('Not found: ' + r);
  Object.assign(job, { running: true, roots, files: 0, dirs: 0, bytes: 0, errors: 0, current: '', startedAt: Date.now(), phase: 'walking' });
  (async () => {
    try {
      const w = await walk(roots);
      job.phase = 'aggregating';
      const totals = aggregate(w.own);
      job.phase = 'checking duplicates';
      const duplicates = await findDuplicates(w.dupPool);
      const sizeOf = (p) => totals.get(lower(p)) ?? null;
      const sizes = {};
      for (const [k, v] of totals) if (v >= SIZE_KEEP_BYTES) sizes[k] = v;

      const artifacts = w.artifacts
        .map((a) => ({ ...a, size: sizeOf(a.path) || 0, ...ARTIFACT_INFO[a.kind] }))
        .filter((a) => a.size > 0)
        .sort((a, b) => b.size - a.size);
      const appCaches = w.appCaches
        .map((c) => {
          const rel = path.relative(isUnder(c.path, LOCAL) ? LOCAL : ROAMING, c.path).split('\\');
          return { path: c.path, app: rel.slice(0, Math.min(rel.length - 1, 2)).join(' / ') || rel[0], size: sizeOf(c.path) || 0 };
        })
        .filter((c) => c.size >= 5 * 1024 ** 2)
        .sort((a, b) => b.size - a.size);
      const known = KNOWN_LOCATIONS
        .filter((k) => roots.some((r) => isUnder(k.path, r)) && fs.existsSync(k.path))
        .map((k) => ({ ...k, size: sizeOf(k.path) || 0 }))
        .filter((k) => k.size > 0);

      scan = {
        roots, startedAt: job.startedAt, finishedAt: Date.now(), files: job.files, dirs: job.dirs, bytes: job.bytes, errors: job.errors,
        sizes, types: w.types,
        largeFiles: w.largeFiles.sort((a, b) => b.size - a.size).slice(0, 500),
        oldDownloads: w.oldDownloads.sort((a, b) => b.size - a.size).slice(0, 500),
        duplicates: duplicates.slice(0, 200),
        artifacts, appCaches, known,
      };
      fs.writeFileSync(SCAN_FILE, JSON.stringify(scan));
      job.phase = 'done';
    } catch (e) {
      job.phase = 'error: ' + e.message;
    } finally {
      job.running = false;
    }
  })();
  return { ok: true };
}

function status() {
  return { ...job, lastScan: scan ? { roots: scan.roots, finishedAt: scan.finishedAt, files: scan.files, bytes: scan.bytes } : null };
}

function knownSize(p) {
  if (!scan) return { size: null, small: false };
  const covered = scan.roots.some((r) => isUnder(p, r));
  if (!covered) return { size: null, small: false };
  const v = scan.sizes[lower(path.resolve(p))];
  return v !== undefined ? { size: v, small: false } : { size: null, small: true };
}

async function listDir(dir) {
  if (typeof dir !== 'string' || !path.isAbsolute(dir)) throw new Error('Expected an absolute path');
  dir = path.resolve(dir);
  const entries = await fsp.readdir(dir, { withFileTypes: true });
  const items = await mapLimit(entries, 64, async (e) => {
    const full = path.join(dir, e.name);
    try {
      const st = await fsp.lstat(full);
      const isLink = st.isSymbolicLink();
      const isDir = !isLink && st.isDirectory();
      const known = isDir ? knownSize(full) : { size: st.size, small: false };
      return { name: e.name, path: full, isDir, isLink, size: known.size, sizeSmall: known.small, mtime: st.mtimeMs, ctime: st.birthtimeMs };
    } catch (err) {
      return { name: e.name, path: full, isDir: e.isDirectory(), isLink: false, size: null, error: err.code || 'ERR' };
    }
  });
  const self = knownSize(dir);
  return { path: dir, parent: path.dirname(dir) !== dir ? path.dirname(dir) : null, size: self.size, items, scannedAt: scan ? scan.finishedAt : null };
}

// Keep saved scan results consistent after something is moved out (trash) or back (restore),
// so the UI updates instantly instead of needing a full rescan.
function adjustForMove(p, size, removed) {
  if (!scan) return;
  const key = lower(path.resolve(p));
  const delta = removed ? -(size || 0) : (size || 0);
  let parent = key;
  while (true) {
    const i = parent.lastIndexOf('\\');
    if (i <= 2) break;
    parent = parent.slice(0, i);
    if (scan.sizes[parent] !== undefined) scan.sizes[parent] = Math.max(0, scan.sizes[parent] + delta);
  }
  if (removed) {
    for (const k of Object.keys(scan.sizes)) if (k === key || k.startsWith(key + '\\')) delete scan.sizes[k];
    const keep = (x) => !isUnder(x.path, p);
    scan.artifacts = scan.artifacts.filter(keep);
    scan.appCaches = scan.appCaches.filter(keep);
    scan.largeFiles = scan.largeFiles.filter(keep);
    scan.oldDownloads = scan.oldDownloads.filter(keep);
    scan.duplicates = scan.duplicates.map((g) => ({ ...g, files: g.files.filter(keep) })).filter((g) => g.files.length > 1)
      .map((g) => ({ ...g, wasted: g.size * (g.files.length - 1) }));
    scan.known = scan.known.map((k) => (isUnder(k.path, p) ? { ...k, size: 0 } : k));
  } else if (size) {
    scan.sizes[key] = size;
  }
  fs.writeFile(SCAN_FILE, JSON.stringify(scan), () => {});
}

function results() {
  if (!scan) return null;
  const { sizes, ...rest } = scan;
  // A generic "cache" folder inside a known location (e.g. AppData\Local\uv\cache) is already
  // counted by that location's entry - drop it so totals don't double count.
  rest.appCaches = rest.appCaches.filter((c) => !KNOWN_LOCATIONS.some((k) => isUnder(c.path, k.path) || isUnder(k.path, c.path)));
  rest.artifacts = rest.artifacts.filter((a) => !isInstallArea(a.path) && (a.kind !== 'node_modules' || !NESTED_NODE_MODULES.test(path.dirname(a.path) + '\\')));
  return rest;
}

